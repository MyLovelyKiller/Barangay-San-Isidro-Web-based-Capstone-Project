<h1>Privacy Policy</h1>
<p>
This Privacy Policy explains how Barangay San Isidro Web-based Management System collects,
uses, stores, and protects the personal information of its users.
</p>

<h2>Information We Collect</h2>
<p>We may collect the following personal information from residents and officials:</p>
<ul>
  <li>Full name</li>
  <li>Sex</li>
  <li>Birthdate</li>
  <li>Contact number</li>
  <li>Email address</li>
  <li>Home address</li>
  <li>Username and password</li>
  <li>Government ID or proof of residency uploaded by the user</li>
  <li>Requests, reports, and submitted documents</li>
</ul>

<h2>Purpose of Collection</h2>
<p>Your personal information is collected for the following purposes:</p>
<ul>
  <li>To create and manage user accounts</li>
  <li>To verify resident and official identity</li>
  <li>To process barangay document requests and reports</li>
  <li>To send updates regarding submitted requests</li>
  <li>To improve website services and system security</li>
</ul>

<h2>How We Protect Your Data</h2>
<p>
We apply reasonable organizational, physical, and technical security measures to protect
your personal information from unauthorized access, disclosure, alteration, or destruction.
</p>

<h2>Sharing of Information</h2>
<p>
Your information will only be accessed by authorized barangay personnel and will not be shared
with unauthorized third parties unless required by law or necessary for official processing.
</p>

<h2>Data Retention</h2>
<p>
Personal data will be retained only for as long as necessary to fulfill the purpose for which
it was collected and to comply with legal or administrative requirements.
</p>

<h2>Your Rights</h2>
<p>You may request access, correction, or updating of your personal data, subject to applicable laws and barangay policies.</p>

<h2>Cookies</h2>
<p>
This website may use cookies for login sessions, security, and website functionality.
For more information, please see our Cookie Policy.
</p>

<h2>Contact Us</h2>
<p>
If you have questions about this Privacy Policy, you may contact Barangay San Isidro through the official barangay office.
</p>

